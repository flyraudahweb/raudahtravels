import { createRequire } from "node:module";
import { writeFile, readFile, unlink } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { randomUUID } from "node:crypto";

const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(
  new URL("../artifacts/api-server/package.json", import.meta.url),
);
const { build } = require("esbuild");
const temporary = path.join(root, `.ota-doc-export-${randomUUID()}.cjs`);
process.env.APP_URL =
  process.env.OTA_DOCS_APP_URL || "https://flyraudah.com.ng";
try {
  await build({
    stdin: {
      contents:
        "export * from './artifacts/api-server/src/services/ota/apiDocumentation'; export * from './artifacts/api-server/src/services/ota/apiDeveloperTools';",
      resolveDir: root,
      sourcefile: "ota-docs-entry.ts",
    },
    bundle: true,
    platform: "node",
    format: "cjs",
    outfile: temporary,
    logLevel: "silent",
  });
  const docs = require(temporary),
    spec = docs.otaOpenApi();
  await writeFile(
    path.join(root, "docs/ota-openapi.json"),
    JSON.stringify(spec, null, 2) + "\n",
  );
  await writeFile(
    path.join(root, "docs/OTA_MOBILE_API.md"),
    docs.mobileIntegrationGuide(),
  );
  await writeFile(
    path.join(root, "docs/flyraudah-ota.postman_collection.json"),
    JSON.stringify(docs.otaPostmanCollection(), null, 2) + "\n",
  );
  await writeFile(
    path.join(root, "docs/flyraudah-ota.postman_environment.json"),
    JSON.stringify(docs.otaPostmanEnvironment(), null, 2) + "\n",
  );
  const { default: openapiTS, astToString } = require("openapi-typescript");
  const types = astToString(await openapiTS(spec));
  await writeFile(path.join(root, "docs/mobile/flyraudah-api.d.ts"), types);
  const assets = {
    "flyraudah-api.d.ts": types,
    "flyraudah-client.ts": await readFile(
      path.join(root, "docs/mobile/flyraudah-client.ts"),
      "utf8",
    ),
    "README.md": await readFile(
      path.join(root, "docs/mobile/README.md"),
      "utf8",
    ),
  };
  await writeFile(
    path.join(
      root,
      "artifacts/api-server/src/services/ota/mobileClientAssets.ts",
    ),
    "// Generated by pnpm run docs:ota. Do not edit by hand.\nexport const MOBILE_CLIENT_FILES = " +
      JSON.stringify(assets, null, 2) +
      " as const;\n",
  );
  console.log(
    `Exported OTA v${spec.info.version}: docs/ota-openapi.json and docs/OTA_MOBILE_API.md`,
  );
} finally {
  await unlink(temporary).catch(() => {});
}
